const STORAGE_KEY = 'magical_birthday_surprise_data_v3';

export function loadSurpriseData(): SurpriseConfig {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      return { ...DEFAULT_SURPRISE_DATA, ...parsed };
    }
  } catch (e) {
    console.error("Failed to load custom surprise data", e);
  }
  return DEFAULT_SURPRISE_DATA;
}

export function saveSurpriseData(data: SurpriseConfig) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (e) {
    console.error("Failed to save custom surprise data", e);
  }
}
